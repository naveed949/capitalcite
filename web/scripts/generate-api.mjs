import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(webRoot, "..");
const schemaPath = resolve(webRoot, "src/api/schema.ts");
const check = process.argv.includes("--check");
const write = process.argv.includes("--write");

if (check === write) {
  process.stderr.write("usage: node scripts/generate-api.mjs --write|--check\n");
  process.exit(2);
}

const env = { ...process.env };
const home = env.HOME ?? "";
env.PATH = `${home}/.local/bin:${env.PATH ?? ""}`;
if (!env.SEC_USER_AGENT) {
  env.SEC_USER_AGENT = "capitalcite-openapi generate@example.com";
}

const dumped = spawnSync("uv", ["run", "python", "scripts/dump_openapi.py"], {
  cwd: repoRoot,
  env,
  encoding: "utf8",
  maxBuffer: 32 * 1024 * 1024,
});

if (dumped.status !== 0) {
  process.stderr.write(dumped.stdout ?? "");
  process.stderr.write(dumped.stderr ?? "");
  process.exit(dumped.status ?? 1);
}

const spec = JSON.parse(dumped.stdout);
const ast = await openapiTS(spec);
const banner =
  "/**\n * Generated by `pnpm --dir web generate:api`. Do not edit this file by hand.\n */\n";
const output = `${banner}${astToString(ast)}`;

if (check) {
  const dir = mkdtempSync(resolve(tmpdir(), "capitalcite-openapi-"));
  const temp = resolve(dir, "schema.ts");
  writeFileSync(temp, output);
  const diff = spawnSync("diff", ["-u", schemaPath, temp], { encoding: "utf8" });
  rmSync(dir, { recursive: true, force: true });
  if (diff.stdout) process.stderr.write(diff.stdout);
  if (diff.stderr) process.stderr.write(diff.stderr);
  process.exit(diff.status === 0 ? 0 : 1);
}

mkdirSync(dirname(schemaPath), { recursive: true });
writeFileSync(schemaPath, output);
process.stdout.write(`wrote ${schemaPath}\n`);
